export type MsgKey = keyof typeof DICT.zh;

export function t(key: keyof typeof DICT.zh, lang?: Lang) {
  const current = lang ?? loadDisplayPrefs().lang;
  return DICT[current][key];
}

/**
 * 带占位符的文案：把 {name} 换成传入的值。
 * 例：tf("authSmsSent", { email: "1@qq.com" }) → 「验证码已发送到 1@qq.com」。
 * 只在确实需要插值的句子上用，普通文案仍走 t()。
 */
export function tf(key: keyof typeof DICT.zh, params: Record<string, string>, lang?: Lang) {
  return Object.entries(params).reduce((text, [name, value]) => text.split(`{${name}}`).join(value), t(key, lang));
}
